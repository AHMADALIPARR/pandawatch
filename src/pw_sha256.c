static uint32_t rotr32(uint32_t x, unsigned n) { return (x >> n) | (x << (32u - n)); }

static void compress(uint32_t st[8], const uint8_t blk[64]) {
    uint32_t w[64];
    for (unsigned i = 0; i < 16; ++i) {
        w[i] = ((uint32_t)blk[4 * i] << 24) | ((uint32_t)blk[4 * i + 1] << 16) |
               ((uint32_t)blk[4 * i + 2] << 8) | (uint32_t)blk[4 * i + 3];
    }
    for (unsigned i = 16; i < 64; ++i) {
        uint32_t s0 = rotr32(w[i - 15], 7) ^ rotr32(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = rotr32(w[i - 2], 17) ^ rotr32(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    uint32_t a = st[0], b = st[1], c = st[2], d = st[3];
    uint32_t e = st[4], f = st[5], g = st[6], h = st[7];
    for (unsigned i = 0; i < 64; ++i) {
        uint32_t S1 = rotr32(e, 6) ^ rotr32(e, 11) ^ rotr32(e, 25);
        uint32_t ch = (e & f) ^ (~e & g);
        uint32_t t1 = h + S1 + ch + K[i] + w[i];
        uint32_t S0 = rotr32(a, 2) ^ rotr32(a, 13) ^ rotr32(a, 22);
        uint32_t mj = (a & b) ^ (a & c) ^ (b & c);
        uint32_t t2 = S0 + mj;
        h = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }
    st[0] += a; st[1] += b; st[2] += c; st[3] += d;
    st[4] += e; st[5] += f; st[6] += g; st[7] += h;
}

void pw_sha256_init(pw_sha256_ctx *ctx) {
    static const uint32_t iv[8] = {
        0x6a09e667u, 0xbb67ae85u, 0x3c6ef372u, 0xa54ff53au,
        0x510e527fu, 0x9b05688cu, 0x1f83d9abu, 0x5be0cd19u
    };
    memcpy(ctx->state, iv, sizeof iv);
    ctx->total_len = 0;
    ctx->block_len = 0;
    memset(ctx->block, 0, sizeof ctx->block);
}

void pw_sha256_update(pw_sha256_ctx *ctx, const void *data, size_t len) {
    const uint8_t *p = (const uint8_t *)data;
    ctx->total_len += (uint64_t)len;
    while (len > 0) {
        size_t take = 64u - ctx->block_len;
        if (take > len) take = len;
        memcpy(ctx->block + ctx->block_len, p, take);
        ctx->block_len += take;
        p += take;
        len -= take;
        if (ctx->block_len == 64u) {
            compress(ctx->state, ctx->block);
            ctx->block_len = 0;
        }
    }
}

void pw_sha256_final(pw_sha256_ctx *ctx, uint8_t out[32]) {
    uint64_t bits = ctx->total_len * 8u;
    ctx->block[ctx->block_len++] = 0x80u;
    if (ctx->block_len > 56u) {
        memset(ctx->block + ctx->block_len, 0, 64u - ctx->block_len);
        compress(ctx->state, ctx->block);
        ctx->block_len = 0;
    }
    memset(ctx->block + ctx->block_len, 0, 56u - ctx->block_len);
    for (unsigned i = 0; i < 8; ++i) {
        ctx->block[56 + i] = (uint8_t)(bits >> (56u - 8u * i));
    }
    compress(ctx->state, ctx->block);
    for (unsigned i = 0; i < 8; ++i) {
        out[4 * i]     = (uint8_t)(ctx->state[i] >> 24);
        out[4 * i + 1] = (uint8_t)(ctx->state[i] >> 16);
        out[4 * i + 2] = (uint8_t)(ctx->state[i] >> 8);
        out[4 * i + 3] = (uint8_t)(ctx->state[i]);
    }
    memset(ctx, 0, sizeof *ctx);
}

void pw_sha256(const void *data, size_t len, uint8_t out[32]) {
    pw_sha256_ctx ctx;
    pw_sha256_init(&ctx);
    pw_sha256_update(&ctx, data, len);
    pw_sha256_final(&ctx, out);
}

void pw_hex32(const uint8_t digest[32], char out[65]) {
    static const char hx[] = "0123456789abcdef";
    for (unsigned i = 0; i < 32; ++i) {
        out[2 * i]     = hx[digest[i] >> 4];
        out[2 * i + 1] = hx[digest[i] & 0x0Fu];
    }
    out[64] = '\0';
}
